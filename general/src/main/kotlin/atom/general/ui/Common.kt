/** A row whose value opens a menu of options. */
@Composable
internal fun <T> ChoiceRow(
    title: String,
    value: String,
    options: List<Pair<T, String>>,
    selected: T,
    onSelect: (T) -> Unit,
    subtitle: String? = null,
    enabled: Boolean = true,
) {
    var open by remember { mutableStateOf(false) }
    Box {
        GroupRow(
            title = title,
            subtitle = subtitle,
            enabled = enabled,
            onClick = { open = true },
            trailing = { RowValue(value) },
        )
        AtomMenu(expanded = open, onDismiss = { open = false }) {
            options.forEach { (option, label) ->
                AtomMenuItem(label, checked = option == selected) {
                    open = false
                    onSelect(option)
                }
            }
        }
    }
}

/** Small grey explanatory text under a group. */
@Composable
internal fun FootNote(text: String, modifier: Modifier = Modifier) {
    Text(
        text,
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        modifier = modifier.padding(start = 18.dp, end = 18.dp, top = 8.dp),
    )
}

internal fun appVersion(context: Context): String =
    runCatching { context.packageManager.getPackageInfo(context.packageName, 0).versionName }.getOrNull() ?: "0"

/** Opens an https link or a mailto address; tells the user when nothing can handle it. */
internal fun openExternal(context: Context, target: String, subject: String? = null) {
    val t = target.trim()
    val intent = if (t.contains('@') && !t.contains("://")) {
        Intent(Intent.ACTION_SENDTO, Uri.parse("mailto:" + t.removePrefix("mailto:"))).apply {
            if (subject != null) putExtra(Intent.EXTRA_SUBJECT, subject)
        }
    } else {
        Intent(Intent.ACTION_VIEW, Uri.parse(t))
    }
    try {
        context.startActivity(intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    } catch (e: ActivityNotFoundException) {
        Toast.makeText(context, R.string.about_open_failed, Toast.LENGTH_SHORT).show()
    }
}

